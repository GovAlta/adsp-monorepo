// ── Helper: paginate ──────────────────────────────────────────────────────────
function paginate(items, page = 1, pageSize = 20) {
  const p = Math.max(1, parseInt(page) || 1);
  const ps = Math.min(100, Math.max(1, parseInt(pageSize) || 20));
  const start = (p - 1) * ps;
  return {
    items: items.slice(start, start + ps),
    total: items.length,
    page: p,
    pageSize: ps,
  };
}

